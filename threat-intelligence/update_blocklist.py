"""
Downloads public lists of anonymizing networks into anonymizer_blocklist_feeds.txt.

Sources:
  Tor exit nodes   https://check.torproject.org/torbulkexitlist   (Tor Project, one IP per line)
  VPN ranges       https://raw.githubusercontent.com/X4BNet/lists_vpn/main/output/vpn/ipv4.txt
                   (X4BNet/lists_vpn, MIT licence, CIDR ranges of known VPN networks)

Usage:
    python3 threat-intelligence/update_blocklist.py              # Tor + VPN
    python3 threat-intelligence/update_blocklist.py --tor-only   # skip the VPN list
    python3 threat-intelligence/update_blocklist.py --vpn-url <url>   # use a different VPN list

Run it once while you have internet. The result is a plain local file, so
the blocking keeps working offline afterwards (e.g. at a demo with no Wi-Fi).

A feed that fails to download is skipped and its old entries are kept; the
file is only rewritten if at least one feed succeeded.

Heads up: a VPN list blocks real people who use a VPN. If that is a problem,
use --tor-only or delete lines from the generated file.
"""

import argparse
import ipaddress
import os
import sys
from datetime import datetime, timezone

import requests

HERE = os.path.dirname(os.path.abspath(__file__))
FEEDS_FILE = os.path.join(HERE, "anonymizer_blocklist_feeds.txt")

TOR_URL = "https://check.torproject.org/torbulkexitlist"
VPN_URL = "https://raw.githubusercontent.com/X4BNet/lists_vpn/main/output/vpn/ipv4.txt"
TIMEOUT = 30


def parse_networks(text: str) -> list[str]:
    """Pulls valid IPs / CIDRs out of a feed, one per line, ignoring comments and junk."""
    found = []
    for line in text.splitlines():
        token = line.strip().split("#")[0].strip().split()
        if not token:
            continue
        try:
            found.append(str(ipaddress.ip_network(token[0], strict=False)))
        except ValueError:
            continue
    return found


def fetch(url: str) -> list[str] | None:
    try:
        resp = requests.get(url, timeout=TIMEOUT, headers={"User-Agent": "AI-SOAR-blocklist-updater"})
        resp.raise_for_status()
        return parse_networks(resp.text)
    except requests.RequestException as exc:
        print(f"  FAILED: {exc}")
        return None


def read_existing() -> dict[str, list[str]]:
    """Keeps the previous entries of a feed if its download fails this time."""
    old: dict[str, list[str]] = {"tor": [], "vpn": []}
    if not os.path.exists(FEEDS_FILE):
        return old
    with open(FEEDS_FILE, encoding="utf-8", errors="ignore") as f:
        for line in f:
            parts = line.split()
            if len(parts) >= 2 and not line.startswith("#") and parts[1] in old:
                old[parts[1]].append(parts[0])
    return old


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tor-only", action="store_true", help="skip the VPN list")
    ap.add_argument("--vpn-url", default=VPN_URL, help="override the VPN list URL")
    args = ap.parse_args()

    previous = read_existing()
    result = {"tor": previous["tor"], "vpn": [] if args.tor_only else previous["vpn"]}
    any_success = False

    print(f"Tor exit nodes  <- {TOR_URL}")
    tor = fetch(TOR_URL)
    if tor:
        result["tor"] = tor
        any_success = True
        print(f"  {len(tor)} entries")

    if not args.tor_only:
        print(f"VPN ranges      <- {args.vpn_url}")
        vpn = fetch(args.vpn_url)
        if vpn:
            result["vpn"] = vpn
            any_success = True
            print(f"  {len(vpn)} entries")

    if not any_success:
        print("Nothing downloaded; leaving the existing feeds file untouched.")
        return 1

    tmp = FEEDS_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("# Generated by update_blocklist.py -- do not edit by hand (re-run the script instead).\n")
        f.write(f"# Updated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n")
        for net in result["tor"]:
            f.write(f"{net} tor tor-exit-node\n")
        for net in result["vpn"]:
            f.write(f"{net} vpn public-vpn-list\n")
    os.replace(tmp, FEEDS_FILE)
    print(f"Wrote {len(result['tor'])} Tor + {len(result['vpn'])} VPN entries to {FEEDS_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
