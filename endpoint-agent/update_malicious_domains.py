"""
Downloads a public list of malware-hosting domains (abuse.ch URLhaus host file)
into endpoint-agent/malicious_domains_feed.txt, which the agent reads together
with malicious_domains.txt.

    python endpoint-agent/update_malicious_domains.py

Needs internet access. Restart the agent afterwards. Notes:
  * The list changes constantly and can occasionally contain a legitimate site
    that was abused; review hits before acting on them.
  * Domains only (hosts that are bare IP addresses are skipped).
"""

import ipaddress
import os
import sys

import requests

URL = "https://urlhaus.abuse.ch/downloads/hostfile/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "malicious_domains_feed.txt")
MAX_DOMAINS = 200000


def parse_hostfile(text: str) -> list[str]:
    """Hosts-file lines ('127.0.0.1  bad.example') -> domain names."""
    domains = []
    seen = set()
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        name = parts[-1].lower().rstrip(".")
        if name in ("localhost", "localhost.localdomain") or "." not in name:
            continue
        try:
            ipaddress.ip_address(name)
            continue                      # a bare IP, not a domain
        except ValueError:
            pass
        if name not in seen:
            seen.add(name)
            domains.append(name)
        if len(domains) >= MAX_DOMAINS:
            break
    return domains


def main() -> int:
    try:
        resp = requests.get(URL, timeout=30)
        resp.raise_for_status()
    except requests.RequestException as exc:
        print(f"Could not download the list ({exc}).")
        return 1
    domains = parse_hostfile(resp.text)
    if not domains:
        print("The download contained no domains; nothing written.")
        return 1
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("# Generated by update_malicious_domains.py from abuse.ch URLhaus. Do not edit.\n")
        f.write("\n".join(domains) + "\n")
    os.replace(tmp, OUT)
    print(f"Wrote {len(domains)} domains to {OUT}. Restart the agent to load them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
